namespace {
/// Successful ordinary allocations remaining before one injected exception; -1 disables injection.
thread_local std::ptrdiff_t remaining = -1;
/// Whether this attempt actually reached its requested allocation boundary.
thread_local bool injected{};

/// Replace ordinary throwing allocation only within this isolated test executable.
[[gnu::noinline]] void* allocate(std::size_t size) {

    if (remaining == 0) {
        remaining = -1;
        injected = true;
        throw std::bad_alloc{};
    }
    if (remaining > 0) {
        --remaining;
    }
    for (;;) {
        if (void* value = std::malloc(size ? size : 1)) {
            return value;
        }
        if (auto handler = std::get_new_handler()) {
            handler();
        } else {
            throw std::bad_alloc{};
        }
    }
}

/// Release ordinary storage, including null; over-aligned allocation is outside this sweep.
[[gnu::noinline]] void release(void* value) noexcept {
    std::free(value);
}

/// Limit injection to the production call, leaving cleanup and independent oracles uninjected.
class Failure {
public:
    /// Fail after point successful allocations, with a fresh counter for every new sender.
    explicit Failure(std::ptrdiff_t point) {
        remaining = point;
        injected = false;
    }

    /// Disable injection on both normal return and exception unwinding.
    ~Failure() {
        remaining = -1;
    }

    /// Injection ownership cannot be copied or reassigned.
    Failure(const Failure&) = delete;
    Failure& operator=(const Failure&) = delete;
};
} // namespace

/// Ordinary scalar allocation participates in the isolated failure sweep.
void* operator new(std::size_t size) {
    return allocate(size);
}

/// Ordinary array allocation shares the same single-failure counter.
void* operator new[](std::size_t size) {
    return allocate(size);
}

/// Release scalar storage in its original allocation domain.
void operator delete(void* value) noexcept {
    release(value);
}

/// Release array storage in its original allocation domain.
void operator delete[](void* value) noexcept {
    release(value);
}

/// Sized scalar deletion has the same release semantics.
void operator delete(void* value, std::size_t) noexcept {
    release(value);
}

/// Sized array deletion has the same release semantics.
void operator delete[](void* value, std::size_t) noexcept {
    release(value);
}

namespace {
using namespace std::chrono_literals;

/// Distinguish initial, dense, partial and expired pages in both replication domains.
enum class Case {
    /// The initial empty response still allocates its oneof body.
    Empty,
    /// Four records and lightweight mutations exercise repeated fields and all delta forms.
    Delta,
    /// A frozen root starts with one row per page.
    First,
    /// Three acknowledged-to-transport pages precede the faulted final page.
    Last,
    /// Four snapshot rows share one repeated-field allocation sequence.
    Dense,
    /// Expiry retains Catalog watermarks and removes Ephemeris rows.
    Expired
};

/// Observe symmetric retained-root accounting without allocating inside callbacks.
struct Budget {
    /// Bytes currently retained by the single sender.
    std::size_t held{};
    /// A mismatched release is retained as a failure rather than throwing in a callback.
    bool invalid{};

    /// Reserve the next root's actual logical charge.
    static bool reserve(void* context, std::size_t bytes) noexcept {
        static_cast<Budget*>(context)->held += bytes;
        return true;
    }

    /// Return one owned root charge; detect underflow separately.
    static void release(void* context, std::size_t bytes) noexcept {
        auto& budget = *static_cast<Budget*>(context);
        if (bytes > budget.held) {
            budget.invalid = true;
        } else {
            budget.held -= bytes;
        }
    }
};

/// Build a fresh real source and compare packets against literal operations, not another encoder.
template <typename Domain>
class Fixture {
    using State = typename Domain::State;
    using Packet = proto::astra::v1::SessionPacket;

    /// Stepwise business time keeps expiry independent of host scheduling.
    std::chrono::nanoseconds now_ = 1s;
    /// Heap-backed scope names exercise both generated byte setters.
    const astra::Scope scope_{std::string(64, 's'), std::string(64, 'p')};
    /// Literal payloads include present-empty, embedded NUL and non-SSO values.
    const std::array<std::string, 4> values_{"", std::string("a\0b", 3), std::string(96, 'c'), std::string(96, 'd')};
    /// Fixed attributes remain independent of mutable Data.
    const std::string attr_ = std::string(96, 'a');
    /// Expected keys are authored inputs or opaque IDs returned by initial registration only.
    std::array<std::string, 4> keys_;
    /// Real native state owns all sources and histories.
    State state_;
    /// The scenario fixes the allowed sequence before injection starts.
    const Case kind_;

    /// Retain history for deltas and force snapshots for recovery scenarios.
    static typename State::Limits limits(Case kind) {
        typename State::Limits result;
        if (kind != Case::Empty && kind != Case::Delta) {
            result.source.history = 0;
        }
        return result;
    }

    /// Construct immutable input bytes outside the faulted production call.
    static typename Domain::Value bytes(const std::string& value) {
        return std::make_shared<const typename Domain::Buffer>(value.begin(), value.end());
    }

    /// The known source position follows exactly the authored operations and domain expiry rules.
    std::uint64_t head() const {
        if (kind_ == Case::Empty) {
            return 0;
        }
        if (kind_ == Case::Delta) {
            return std::same_as<Domain, astra::Catalog> ? 5 : 7;
        }
        return kind_ == Case::Expired && std::same_as<Domain, astra::Ephemeris> ? 8 : 4;
    }

    /// Match every native record field to its independently authored input and fixed clock.
    void record(const auto& row, std::size_t index) const {
        if constexpr (std::same_as<Domain, astra::Catalog>) {
            CHECK(row.version() == index + 10);
            if (kind_ == Case::Expired) {
                CHECK(row.has_watermark() && !row.has_value());
            } else {
                CHECK(row.has_value() && !row.has_watermark());
                CHECK(row.value().value() == values_[index] && row.value().deadline() == 2000000000);
            }
        } else {
            CHECK(row.attr() == attr_ && row.data() == values_[index]);
            CHECK(row.deadline() == 2000000000 && row.ttl_ms() == 1000);
            CHECK(row.update() == 0 && row.renewal() == 0 && row.generation() == 0);
        }
    }

    /// Read one snapshot page without assuming a native tree enumeration order.
    void snapshot(const Packet& packet, std::vector<std::string>& seen) const {

        const auto& page = [&]() -> const auto& {
            if constexpr (std::same_as<Domain, astra::Catalog>) {
                CHECK(packet.has_catalog_snapshot());
                return packet.catalog_snapshot();
            } else {
                CHECK(packet.has_ephemeris_snapshot());
                return packet.ephemeris_snapshot();
            }
        }();
        CHECK(page.position() == head());
        const auto size = kind_ == Case::Expired && std::same_as<Domain, astra::Ephemeris> ? 0U : 4U;
        CHECK(page.entries_size() == (size == 0 ? 0 : kind_ == Case::First || kind_ == Case::Last ? 1
                                                                                                  : 4));
        for (const auto& entry : page.entries()) {
            const auto& key = [&]() -> const std::string& {
                if constexpr (std::same_as<Domain, astra::Catalog>) {
                    return entry.key();
                } else {
                    return entry.uuid();
                }
            }();
            const auto found = std::ranges::find(keys_, key);
            CHECK(found != keys_.end() && std::ranges::find(seen, key) == seen.end());
            CHECK(entry.scope().sector() == scope_.sector && entry.scope().spectrum() == scope_.spectrum);
            record(entry.record(), static_cast<std::size_t>(found - keys_.begin()));
            seen.push_back(key);
        }
        CHECK(page.complete() == (seen.size() == size));
    }

    /// Delta ordering, lightweight forms and deadlines are independent of serializer internals.
    void changes(const Packet& packet) const {

        const auto& page = [&]() -> const auto& {
            if constexpr (std::same_as<Domain, astra::Catalog>) {
                CHECK(packet.has_catalog_changes());
                return packet.catalog_changes();
            } else {
                CHECK(packet.has_ephemeris_changes());
                return packet.ephemeris_changes();
            }
        }();
        CHECK(page.head() == head() && static_cast<std::uint64_t>(page.entries_size()) == head());
        CHECK(astra::Parcel::valid(page));
        for (int index = 0; index < page.entries_size(); ++index) {
            const auto& entry = page.entries(index);
            const auto& key = [&]() -> const std::string& {
                if constexpr (std::same_as<Domain, astra::Catalog>) {
                    return entry.key();
                } else {
                    return entry.uuid();
                }
            }();
            CHECK(entry.position() == static_cast<unsigned>(index + 1));
            CHECK(entry.scope().sector() == scope_.sector && entry.scope().spectrum() == scope_.spectrum);
            CHECK(key == keys_[index < 4 ? static_cast<std::size_t>(index) : 0]);
            if (index < 4) {
                CHECK(entry.has_record());
                record(entry.record(), static_cast<std::size_t>(index));
            } else if constexpr (std::same_as<Domain, astra::Catalog>) {
                CHECK(entry.has_lease() && entry.lease().version() == 10 && entry.lease().deadline() == 3500000000);
            } else if (index == 4) {
                CHECK(entry.has_data() && entry.data().data() == std::string(96, 'u'));
                CHECK(entry.data().order() == 11 && entry.data().deadline() == 2000000000);
            } else if (index == 5) {
                CHECK(entry.has_lease() && entry.lease().order() == 12 && entry.lease().deadline() == 2500000000);
            } else {
                CHECK(entry.has_erase());
            }
        }
    }

public:
    /// Author the bounded history before any failure is enabled.
    explicit Fixture(Case kind) : state_([this] { return std::optional(astra::Clock::Reading{.time = astra::Clock::Time(now_), .ready = true}); }, limits(kind)), kind_(kind) {

        if (kind == Case::Empty) {
            return;
        }
        for (std::size_t index = 0; index < keys_.size(); ++index) {
            if constexpr (std::same_as<Domain, astra::Catalog>) {
                keys_[index] = std::string(80, 'k') + std::to_string(index);
                CHECK(state_.publish(scope_, keys_[index], bytes(values_[index]), index + 10, 1000));
            } else {
                const auto created = state_.create(scope_, bytes(attr_), bytes(values_[index]), 1000);
                CHECK(created);
                keys_[index] = created->uuid;
            }
        }
        if (kind == Case::Delta) {
            if constexpr (std::same_as<Domain, astra::Catalog>) {
                now_ = 1500ms;
                CHECK(state_.renew(scope_, keys_[0], 10, 2000));
            } else {
                CHECK(state_.update(scope_, keys_[0], bytes(std::string(96, 'u')), 11));
                now_ = 1500ms;
                CHECK(state_.renew(scope_, keys_[0], 12));
                CHECK(state_.remove(scope_, keys_[0]));
            }
        } else if (kind == Case::Expired) {
            now_ = 5s;
            state_.tick();
        }
        CHECK(state_.source().position() == head());
    }

    /// Fault one production allocation, retry on the same sender and drain the complete original boundary.
    bool run(unsigned point) {

        Budget budget;
        bool failed{};
        {
            astra::Dispatch<Domain> stream(state_, 8192, kind_ == Case::First || kind_ == Case::Last ? 1 : 8192, &budget, Budget::reserve, Budget::release);
            CHECK(stream.resume(0));
            std::vector<std::string> seen;
            if (kind_ == Case::Last) {
                for (unsigned index = 0; index < 3; ++index) {
                    const auto page = stream.prepare();
                    CHECK(page && *page);
                    snapshot(**page, seen);
                    stream.dispatched();
                    CHECK(stream.sent() == 0 && !stream.acknowledge(head()));
                }
            }
            try {
                const Failure failure(point);
                static_cast<void>(stream.prepare());
            } catch (const std::bad_alloc&) {
                failed = true;
            }
            CHECK(failed == injected);
            CHECK(stream.sent() == 0 && stream.acknowledged() == 0 && !budget.invalid);
            const auto prepared = stream.prepare();
            CHECK(prepared && *prepared);
            CHECK(stream.prepare().value() == *prepared);
            if (kind_ == Case::Empty || kind_ == Case::Delta) {
                changes(**prepared);
                stream.dispatched();
            } else {
                for (unsigned pages = 0; stream.sent() != head(); ++pages) {
                    CHECK(pages < 4);
                    const auto page = stream.prepare();
                    CHECK(page && *page);
                    snapshot(**page, seen);
                    stream.dispatched();
                }
                CHECK(budget.held == 0);
            }
            CHECK(stream.sent() == head() && stream.acknowledge(head()) && stream.acknowledged() == head());
            CHECK(stream.prepare() && stream.prepare().value() == nullptr);
        }
        CHECK(budget.held == 0 && !budget.invalid);
        return failed;
    }
};

/// Sweep every ordinary allocation up to the first complete attempt, with a fixed non-vacuity bound.
template <typename Domain>
void domain(std::string_view name) {

    constexpr std::array kinds{Case::Empty, Case::Delta, Case::First, Case::Last, Case::Dense, Case::Expired};
    constexpr std::array names{"empty", "delta", "first", "last", "dense", "expired"};
    for (std::size_t index = 0; index < kinds.size(); ++index) {
        unsigned failures{};
        bool completed{};
        for (unsigned point = 0; point < 256; ++point) {
            Fixture<Domain> fixture(kinds[index]);
            std::cout << "ASTRA-DISPATCH-BEGIN {\"domain\":\"" << name << "\",\"case\":\"" << names[index] << "\",\"point\":" << point << "}\n"
                      << std::flush;
            const bool failed = fixture.run(point);
            std::cout << "ASTRA-DISPATCH-END {\"domain\":\"" << name << "\",\"case\":\"" << names[index] << "\",\"point\":" << point << ",\"injected\":" << (failed ? "true" : "false") << "}\n"
                      << std::flush;
            failures += failed;
            if (!failed) {
                completed = true;
                break;
            }
        }
        CHECK(completed && failures > 0);
    }
}
} // namespace

/// Keep global allocator replacement isolated from every service and ordinary test process.
int main() {
    try {
        // Validate every literal scenario before the destructive allocation sweep.
        for (const auto kind : {Case::Empty, Case::Delta, Case::First, Case::Last, Case::Dense, Case::Expired}) {
            CHECK(!Fixture<astra::Catalog>(kind).run(256));
            CHECK(!Fixture<astra::Ephemeris>(kind).run(256));
        }
        std::cout << "ASTRA-DISPATCH-HEALTHY 12\n"
                  << std::flush;
        domain<astra::Catalog>("catalog");
        domain<astra::Ephemeris>("ephemeris");
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
